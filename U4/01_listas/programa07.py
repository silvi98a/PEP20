# Programa 07: Funciones matemáticas
temperaturas = [20, 25, 18, 30, 22]

suma_total = sum(temperaturas)
media = sum(temperaturas) / len(temperaturas)
maximo = max(temperaturas)
minimo = min(temperaturas)

print(f"Temperaturas: {temperaturas}")
print(f"Suma: {suma_total}")
print(f"Media: {media}")
print(f"Máximo: {maximo}")
print(f"Mínimo: {minimo}")