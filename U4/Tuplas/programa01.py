# Programa 01: Creación y tipos de tuplas
tupla_datos = (10, 3.14, "Hola", True)
tupla_vacia = ()
tupla_un_elemento = (5,)
tupla_sin_parentesis = 1, "Python", False

print(f"Tipo 1: {type(tupla_datos)}")
print(f"Tipo 2 (vacia): {type(tupla_vacia)}")
print(f"Tipo 3 (un elemento): {type(tupla_un_elemento)}")
print(f"Tipo 4 (sin paréntesis): {type(tupla_sin_parentesis)}")
