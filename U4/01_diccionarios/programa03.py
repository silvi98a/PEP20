# Programa 03: Añadir y modificar elementos
alumno = {"nombre": "Sofía", "nota": 7.5}
print(f"Antes de los cambios: {alumno}")

# Añadir nuevas claves y valores
alumno["edad"] = 21
alumno["ciudad"] = "Madrid"

# Modificar un valor existente
alumno["nota"] = 9.0

print(f"Después de los cambios: {alumno}")